"""Markdown -> Word (.docx), with the standard library only (zipfile + XML text). No new dependency.

Exports reports, hunt plans, CTE plans and vulnerability reports from the case to Word. It handles what those files
use: headings (# to ####), paragraphs, bullet and numbered lists, tables, code blocks, block quotes, horizontal
rules, **bold**, *italic* and `code`. Citations stay in the text as they are ([FIN-0001]) so a reader can trace every
fact back to the mission data.

The page header and footer carry the classification marking when the document's first line is one (the reporter
writes it there, and only when the analyst gave it). A draft that the analyst has not approved says so at the top.
The text is never interpreted: everything is escaped into XML text runs.
"""

from __future__ import annotations

import io
import re
import zipfile
from datetime import datetime, timezone
from xml.sax.saxutils import escape

GENERATED_SPLIT = "<!-- generated by report_save"
_CTRL = re.compile(r"[\x00-\x08\x0b\x0c\x0e-\x1f￾￿]")  # not allowed in XML 1.0
_INLINE = re.compile(r"(\*\*[^*\n]+\*\*|`[^`\n]+`|\*[^*\s][^*\n]*\*)")
_MARKING = re.compile(r"^\(?(?:UNCLASSIFIED|CUI|CONFIDENTIAL|SECRET|TOP SECRET)\b[A-Z0-9/ ,()-]*$")
_PAGE_W = 9360  # usable width in twentieths of a point (8.5in page, 1in margins)

W = "http://schemas.openxmlformats.org/wordprocessingml/2006/main"
R = "http://schemas.openxmlformats.org/officeDocument/2006/relationships"


def _text(t: str) -> str:
    return escape(_CTRL.sub("", t))


def _run(text: str, bold: bool = False, italic: bool = False, style: str = "") -> str:
    rpr = (f'<w:rStyle w:val="{style}"/>' if style else "") + ("<w:b/>" if bold else "") + ("<w:i/>" if italic else "")
    pieces = text.split("\n")
    body = "<w:br/>".join(f'<w:t xml:space="preserve">{_text(p)}</w:t>' for p in pieces)
    return f"<w:r>{f'<w:rPr>{rpr}</w:rPr>' if rpr else ''}{body}</w:r>"


def _runs(text: str, bold: bool = False) -> str:
    out, pos = [], 0
    for m in _INLINE.finditer(text):
        if m.start() > pos:
            out.append(_run(text[pos:m.start()], bold))
        t = m.group(0)
        if t.startswith("**"):
            out.append(_run(t[2:-2], True))
        elif t.startswith("`"):
            out.append(_run(t[1:-1], bold, style="CodeChar"))
        else:
            out.append(_run(t[1:-1], bold, True))
        pos = m.end()
    if pos < len(text):
        out.append(_run(text[pos:], bold))
    return "".join(out)


def _para(text: str, style: str = "", extra_ppr: str = "", bold: bool = False, raw: bool = False) -> str:
    ppr = (f'<w:pStyle w:val="{style}"/>' if style else "") + extra_ppr
    runs = _run(text, bold) if raw else _runs(text, bold)
    return f"<w:p>{f'<w:pPr>{ppr}</w:pPr>' if ppr else ''}{runs}</w:p>"


def _table(rows: list[list[str]]) -> str:
    cols = max(len(r) for r in rows)
    width = _PAGE_W // cols
    grid = "".join(f'<w:gridCol w:w="{width}"/>' for _ in range(cols))
    out = [f'<w:tbl><w:tblPr><w:tblStyle w:val="TableGrid"/><w:tblW w:w="{width * cols}" w:type="dxa"/>'
           f'<w:tblLook w:val="04A0" w:firstRow="1" w:lastRow="0" w:firstColumn="0" w:lastColumn="0" w:noHBand="0" '
           f'w:noVBand="1"/></w:tblPr><w:tblGrid>{grid}</w:tblGrid>']
    for i, row in enumerate(rows):
        head = i == 0
        cells = row + [""] * (cols - len(row))
        out.append("<w:tr>" + ("<w:trPr><w:tblHeader/></w:trPr>" if head else ""))
        for c in cells:
            out.append(f'<w:tc><w:tcPr><w:tcW w:w="{width}" w:type="dxa"/></w:tcPr>{_para(c, "TableText", bold=head)}</w:tc>')
        out.append("</w:tr>")
    out.append("</w:tbl>")
    return "".join(out) + _para("", "Spacer")


# Child elements follow the order the WordprocessingML schema requires (Word rejects a file that does not).
class _Numbering:
    """Bullet lists share one numbering; each numbered list restarts at 1."""

    def __init__(self) -> None:
        self.nums: list[int] = []  # abstractNum id per w:num (1-based ids)

    def new(self, ordered: bool) -> int:
        self.nums.append(1 if ordered else 0)
        return len(self.nums)

    def xml(self) -> str:
        abstract = []
        for aid, (fmt, text) in enumerate((("bullet", "•"), ("decimal", "%1."))):
            abstract.append(f'<w:abstractNum w:abstractNumId="{aid}"><w:multiLevelType w:val="singleLevel"/>'
                            f'<w:lvl w:ilvl="0"><w:start w:val="1"/><w:numFmt w:val="{fmt}"/><w:lvlText w:val="{text}"/>'
                            f'<w:lvlJc w:val="left"/><w:pPr><w:ind w:left="720" w:hanging="360"/></w:pPr></w:lvl>'
                            f'</w:abstractNum>')
        nums = [f'<w:num w:numId="{i}"><w:abstractNumId w:val="{a}"/>'
                + ('<w:lvlOverride w:ilvl="0"><w:startOverride w:val="1"/></w:lvlOverride>' if a == 1 else "")
                + "</w:num>" for i, a in enumerate(self.nums, 1)]
        return f'<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n<w:numbering xmlns:w="{W}">' \
               + "".join(abstract) + "".join(nums) + "</w:numbering>"


def marking_of(md: str) -> str:
    """The classification marking on the document's first line, if it has one."""
    first = next((ln.strip().strip("*#_ ").strip() for ln in md.splitlines() if ln.strip()), "")
    return first if len(first) <= 120 and _MARKING.match(first) else ""


def body_xml(md: str, numbering: _Numbering) -> str:
    lines = md.replace("\r", "").split("\n")
    out: list[str] = []
    i, para = 0, []
    list_id, list_ordered = 0, None

    def flush() -> None:
        nonlocal para
        if para:
            out.append(_para(" ".join(para)))
            para = []

    while i < len(lines):
        ln = lines[i]
        if re.match(r"^\s*```", ln):
            flush()
            list_ordered = None
            i += 1
            buf = []
            while i < len(lines) and not re.match(r"^\s*```", lines[i]):
                buf.append(lines[i])
                i += 1
            out.extend(_para(b, "Code", raw=True) for b in (buf or [""]))
            i += 1
            continue
        h = re.match(r"^(#{1,4})\s+(.*)$", ln)
        if h:
            flush()
            list_ordered = None
            out.append(_para(h.group(2).strip(), f"Heading{len(h.group(1))}"))
            i += 1
            continue
        if re.match(r"^\s*(-{3,}|\*{3,}|_{3,})\s*$", ln):
            flush()
            list_ordered = None
            out.append(_para("", extra_ppr='<w:pBdr><w:bottom w:val="single" w:sz="6" w:space="1" w:color="999999"/></w:pBdr>'))
            i += 1
            continue
        if re.match(r"^\s*\|.*\|\s*$", ln):
            flush()
            list_ordered = None
            rows = []
            while i < len(lines) and re.match(r"^\s*\|.*\|\s*$", lines[i]):
                cells = [c.strip() for c in lines[i].strip()[1:-1].split("|")]
                if not all(re.match(r"^:?-{2,}:?$", c) for c in cells):
                    rows.append(cells)
                i += 1
            if rows:
                out.append(_table(rows))
            continue
        if re.match(r"^\s*>\s?", ln):
            flush()
            list_ordered = None
            buf = []
            while i < len(lines) and re.match(r"^\s*>\s?", lines[i]):
                buf.append(re.sub(r"^\s*>\s?", "", lines[i]))
                i += 1
            out.append(_para(" ".join(buf), "Quote"))
            continue
        li = re.match(r"^\s*([-*+]|\d+[.)])\s+(.*)$", ln)
        if li:
            flush()
            ordered = bool(re.match(r"\d", li.group(1)))
            if list_ordered is not ordered:
                list_id, list_ordered = numbering.new(ordered), ordered
            out.append(_para(li.group(2), "ListParagraph",
                             f'<w:numPr><w:ilvl w:val="0"/><w:numId w:val="{list_id}"/></w:numPr>'))
            i += 1
            continue
        if not ln.strip():
            flush()
            list_ordered = None
            i += 1
            continue
        list_ordered = None
        para.append(ln.strip())
        i += 1
    flush()
    return "".join(out)


