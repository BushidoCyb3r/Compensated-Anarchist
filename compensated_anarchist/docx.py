def _hdr(tag: str, marking: str) -> str:
    return (f'<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n<w:{tag} xmlns:w="{W}" xmlns:r="{R}">'
            f'{_para(marking, "Marking", raw=True)}</w:{tag}>')


def to_docx(md: str, title: str = "", draft_notice: str = "", keep_generated: tuple[str, ...] = ("Sources",)) -> bytes:
    """A .docx of the markdown. The report writer's generated tail (Sources / Verification) keeps only the sections
    named in keep_generated. draft_notice: a line shown at the top (e.g. that the analyst has not approved it)."""
    main, _, tail = md.partition(GENERATED_SPLIT)
    if tail:
        tail = tail.split("-->", 1)[-1]
        kept = [sec for sec in re.split(r"(?m)^(?=## )", tail)
                if (m := re.match(r"## (.+)", sec)) and m.group(1).strip() in keep_generated]
        main = main.rstrip() + "\n\n" + "\n".join(kept)
    main = re.sub(r"<!--.*?-->", "", main, flags=re.S)
    marking = marking_of(main)
    numbering = _Numbering()
    body = (_para(draft_notice, "Notice", raw=True) if draft_notice else "") + body_xml(main, numbering)
    refs = ('<w:headerReference w:type="default" r:id="rIdHeader"/><w:footerReference w:type="default" r:id="rIdFooter"/>'
            if marking else "")
    document = (f'<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n<w:document xmlns:w="{W}" xmlns:r="{R}"><w:body>'
                f'{body}<w:sectPr>{refs}<w:pgSz w:w="12240" w:h="15840"/>'
                f'<w:pgMar w:top="1440" w:right="1440" w:bottom="1440" w:left="1440" w:header="720" w:footer="720" w:gutter="0"/>'
                f'</w:sectPr></w:body></w:document>')
    rels = [("rIdStyles", "styles", "styles.xml"), ("rIdNumbering", "numbering", "numbering.xml")]
    if marking:
        rels += [("rIdHeader", "header", "header1.xml"), ("rIdFooter", "footer", "footer1.xml")]
    doc_rels = ('<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n'
                '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">'
                + "".join(f'<Relationship Id="{i}" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/{t}" '
                          f'Target="{target}"/>' for i, t, target in rels) + "</Relationships>")
    now = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    core = ('<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n'
            '<cp:coreProperties xmlns:cp="http://schemas.openxmlformats.org/package/2006/metadata/core-properties" '
            'xmlns:dc="http://purl.org/dc/elements/1.1/" xmlns:dcterms="http://purl.org/dc/terms/" '
            'xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance">'
            f'<dc:title>{_text(title)}</dc:title><dc:creator>Compensated Anarchist</dc:creator>'
            f'<dcterms:created xsi:type="dcterms:W3CDTF">{now}</dcterms:created></cp:coreProperties>')
    overrides = [("/word/document.xml", "wordprocessingml.document.main+xml"), ("/word/styles.xml", "wordprocessingml.styles+xml"),
                 ("/word/numbering.xml", "wordprocessingml.numbering+xml")]
    if marking:
        overrides += [("/word/header1.xml", "wordprocessingml.header+xml"), ("/word/footer1.xml", "wordprocessingml.footer+xml")]
    types = ('<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n'
             '<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">'
             '<Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>'
             '<Default Extension="xml" ContentType="application/xml"/>'
             + "".join(f'<Override PartName="{p}" ContentType="application/vnd.openxmlformats-officedocument.{t}"/>'
                       for p, t in overrides)
             + '<Override PartName="/docProps/core.xml" ContentType="application/vnd.openxmlformats-package.core-properties+xml"/>'
             "</Types>")
    root_rels = ('<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n'
                 '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">'
                 '<Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" '
                 'Target="word/document.xml"/>'
                 '<Relationship Id="rId2" Type="http://schemas.openxmlformats.org/package/2006/relationships/metadata/core-properties" '
                 'Target="docProps/core.xml"/></Relationships>')
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        z.writestr("[Content_Types].xml", types)
        z.writestr("_rels/.rels", root_rels)
        z.writestr("docProps/core.xml", core)
        z.writestr("word/document.xml", document)
        z.writestr("word/styles.xml", STYLES)
        z.writestr("word/numbering.xml", numbering.xml())
        z.writestr("word/_rels/document.xml.rels", doc_rels)
        if marking:
            z.writestr("word/header1.xml", _hdr("hdr", marking))
            z.writestr("word/footer1.xml", _hdr("ftr", marking))
    return buf.getvalue()
