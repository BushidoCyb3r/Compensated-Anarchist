@dataclass
class Source:
    id: str
    kind: str
    line: str     # one-line description for the index
    text: str     # full text the verifier checks values against


class MissionData:
    def __init__(self, case: Any, history: Any, folders: dict[str, Path], now: Callable[[], datetime] | None = None):
        self.case, self.history, self.folders = case, history, folders
        self.now = now or (lambda: datetime.now(timezone.utc))

    def _case_items(self) -> list[Source]:
        d = self.case.data
        out = [Source("CASE", "case", f"CASE {d['id']}: opened {d['opened'][:10]}, status {d['status']}; mission: "
                      f"{(d.get('mission') or '')[:120]}",
                      f"Case {d['id']}\nopened {d['opened']}\nstatus {d['status']}\nmission: {d.get('mission', '')}")]
        n = self.now()
        out.append(Source("NOW", "date", f"NOW: the report's own date and time ({n.isoformat()[:16]}Z)",
                          f"{n.isoformat()} {n.date().isoformat()} {n.strftime('%d%H%MZ %b %y').upper()}"))
        for f in d.get("findings", []):
            out.append(Source(f["id"], "finding", f"{f['id']} finding [{f['severity']}, verdict {f['verdict']}] {f['title']}",
                              _render(f)))
        for i in d.get("iocs", []):
            out.append(Source(i["id"], "ioc", f"{i['id']} IOC {i['type']}={i['value']} ({i['confidence']})", _render(i)))
        for e in d.get("timeline", []):
            out.append(Source(e["id"], "timeline", f"{e['id']} {e['event_time']} {e['host']} {e['description'][:90]}", _render(e)))
        for e in d.get("evidence", []):
            out.append(Source(e["id"], "evidence", f"{e['id']} evidence {Path(e['path']).name} sha256={e['hashes']['sha256'][:16]}...",
                              _render(e)))
        for x in d.get("notes", []):
            out.append(Source(x["id"], "note", f"{x['id']} note by {x['author']}: {x['text'][:100]}", _render(x)))
        for s in d.get("statements", []):
            out.append(Source(s["id"], "statement", f"{s['id']} analyst statement ({s['by']}, {s['answered_at'][:16]}): "
                              f"{s['question'][:60]} -> {s['answer'][:80]}", _render(s)))
        return out

    def _files(self) -> list[Source]:
        out = []
        for label, folder in self.folders.items():
            if not folder.is_dir():
                continue
            for p in sorted(folder.iterdir()):
                if not p.is_file() or p.is_symlink() or p.stat().st_size > MAX_SOURCE_FILE:
                    continue
                text = p.read_bytes().decode("utf-8", errors="replace")
                out.append(Source(f"FILE:{p.name}", "file", f"FILE:{p.name} ({label}, {p.stat().st_size} bytes) "
                                  f"{huntplans.title(p) if p.suffix == '.md' else ''}", text))
        return out

    def _events(self) -> list[Source]:
        out = []
        if not self.history:
            return out
        for conv in self.history.list(self.case.id, 1000):
            title = (conv.get("title") or "")[:40]
            for e in self.history.events(conv["id"]):
                if e["kind"] not in EVENT_KINDS:
                    continue
                d = e["data"]
                when = datetime.fromtimestamp(e["ts"], timezone.utc).strftime("%Y-%m-%d %H:%MZ")
                if e["kind"] == "analyst_message":
                    who, text = "analyst", str(d.get("text", ""))
                elif e["kind"] == "subagent_report":
                    who = f"{d.get('id', '')} {d.get('expert', '')} report ({d.get('status', '')})"
                    text = "\n".join([str(d.get("summary", "")), str(d.get("details", "")),
                                      *[f"open question: {q}" for q in d.get("open_questions") or []]])
                elif e["kind"] == "text":
                    who, text = str(d.get("agent_id") or d.get("agent", "agent")), str(d.get("text", ""))
                else:
                    who, text = f"{d.get('agent_id', '')} tool {d.get('tool', '')} (result, first 800 chars)", str(d.get("preview", ""))
                if not text.strip():
                    continue
                first = re.sub(r"\s+", " ", text)[:100]
                out.append(Source(f"EV-{e['id']}", e["kind"], f"EV-{e['id']} {when} [{title}] {who}: {first}",
                                  f"{when}\n{who}\n{text}"))
        return out

    def all(self) -> dict[str, Source]:
        return {s.id.upper(): s for s in self._case_items() + self._files() + self._events()}

    def analyst_words(self) -> str:
        """Everything the analyst said in this case (messages and recorded statements): the only source of markings."""
        parts = [s.get("answer", "") for s in self.case.data.get("statements", [])]
        if self.history:
            for conv in self.history.list(self.case.id, 1000):
                parts += [str(e["data"].get("text", "")) for e in self.history.events(conv["id"]) if e["kind"] == "analyst_message"]
        return "\n".join(parts)


def _render(item: dict[str, Any]) -> str:
    lines = []
    for k, v in item.items():
        if isinstance(v, (list, tuple)):
            v = ", ".join(str(x) for x in v)
        elif isinstance(v, dict):
            v = "; ".join(f"{a}={b}" for a, b in v.items())
        lines.append(f"{k}: {v}")
    return "\n".join(lines)


