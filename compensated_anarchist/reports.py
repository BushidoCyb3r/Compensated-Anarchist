@dataclass
class Issue:
    kind: str
    blocking: bool
    line: int
    text: str
    detail: str

    def render(self) -> str:
        return f"- line {self.line} [{self.kind}{'' if self.blocking else ', warning'}] {self.detail}\n    \"{self.text[:200]}\""


def _units(draft: str) -> list[tuple[int, str, bool, bool]]:
    """(line number, statement, exempt, is_code) - sentences, list items, table rows and code blocks. Statements in the
    questions / gaps, sources and verification sections are exempt from the citation checks (not from leak checks)."""
    out: list[tuple[int, str, bool, bool]] = []
    exempt = False
    fence: list[str] | None = None
    start = 0
    for n, raw in enumerate(draft.split(GENERATED)[0].splitlines(), 1):
        line = raw.rstrip()
        if line.lstrip().startswith("```"):
            if fence is None:
                fence, start = [], n
            else:
                out.append((start, "\n".join(fence), exempt, True))
                fence = None
            continue
        if fence is not None:
            fence.append(line)
            continue
        if not line.strip():
            continue
        if re.match(r"^\s{0,3}#{1,6}\s", line):
            exempt = bool(EXEMPT_SECTIONS.search(line))
            continue
        if re.match(r"^\s*\|?\s*:?-{3,}", line):
            continue
        if line.lstrip().startswith("|"):
            out.append((n, line, exempt, False))
            continue
        body = re.sub(r"^\s*(?:[-*+]|\d{1,2}[.)])\s+", "", line)
        for s in re.split(r"(?<=[.!?])\s+(?=[A-Z(\[`\"])", body):
            if out and out[-1][0] == n and not BRACKET.sub("", s).strip(" .;,"):
                prev = out.pop()  # a trailing citation after the full stop belongs to the sentence before it
                out.append((prev[0], prev[1] + " " + s, prev[2], prev[3]))
            else:
                out.append((n, s, exempt, False))
    if fence is not None:
        out.append((start, "\n".join(fence), exempt, True))
    return out


def citations(text: str) -> tuple[list[str], str]:
    """(source ids cited, the text without its citation brackets)."""
    ids: list[str] = []

    def take(m: re.Match[str]) -> str:
        parts = [p.strip() for p in re.split(r"[,;]\s*|\s+and\s+", m.group(1))]
        found = [p for p in parts if SOURCE_ID.match(p)]
        if not found:
            return m.group(0)
        ids.extend(p if p.upper().startswith("FILE:") else p.upper() for p in found)
        return " "
    return ids, BRACKET.sub(take, text)


def example_markers(examples: list[str]) -> tuple[set[tuple[str, str]], set[str]]:
    """Distinctive values and capitalized phrases from the example reports' bodies (not their headings)."""
    vals: set[tuple[str, str]] = set()
    phrases: set[str] = set()
    for text in examples:
        for line in text.splitlines():
            if re.match(r"^\s{0,3}#{1,6}\s", line):
                continue
            for kind, v in values(line):
                if kind in ("count", "time") or (kind == "number" and len(v.replace(",", "")) < 4):
                    continue
                vals.add((kind, v.lower()))
            for m in PHRASE.finditer(line):
                words = re.split(r"[ -]", m.group(0).lower())
                while words and words[0] in LEADING:
                    words.pop(0)
                ph = " ".join(words)
                if len(words) >= 2 and ph not in COMMON_PHRASES:
                    phrases.add(ph)
    return vals, phrases


def verify(draft: str, sources: dict[str, Source], analyst_words: str = "", examples: list[str] | None = None,
           template: str = "", now: datetime | None = None, findings: dict[str, dict[str, Any]] | None = None
           ) -> tuple[list[Issue], set[str]]:
    now = now or datetime.now(timezone.utc)
    issues: list[Issue] = []
    cited_all: set[str] = set()
    corpus = "\n".join(s.text for s in sources.values()).lower()
    ex_vals, ex_phrases = example_markers(examples or [])
    tmpl = template.lower()
    analyst_up = analyst_words.upper()

    def said(mark: str) -> bool:
        word = PORTION.get(mark, mark)
        return bool(re.search(rf"(?<![A-Z]){re.escape(word)}(?![A-Z])", analyst_up)) or \
            (mark in PORTION and f"({mark})" in analyst_up)
    flagged_phrases: set[str] = set()
    warned_unreviewed: set[str] = set()
    prev_ids: list[str] = []
    for n, unit, exempt, is_code in _units(draft):
        ids, bare = citations(unit)
        if not ids and is_code and prev_ids:  # a code block takes the citations of the statement before it
            ids = prev_ids
        cited_all |= set(ids)
        # classification markings: only ever from the analyst
        for m in MARKING.finditer(unit):
            mark = m.group(1) or m.group(2)
            if not said(mark):
                issues.append(Issue("marking", True, n, unit, f"classification marking '{mark}' was not given by the analyst. "
                                    "Markings come only from the analyst: ask for them, record the answer with "
                                    "case_analyst_statement, and cite it."))
        vals = values(MARKING.sub(" ", bare))
        # leaks from the example reports (checked everywhere, including questions)
        for kind, v in vals:
            if (kind, v.lower()) in ex_vals and v.lower() not in corpus:
                issues.append(Issue("example_leak", True, n, unit, f"'{v}' comes from an example report, not from this "
                                    "mission's data. Example reports are format only: remove it."))
        for ph in ex_phrases:
            if ph in unit.lower() and ph not in corpus and ph not in tmpl and ph not in flagged_phrases:
                flagged_phrases.add(ph)
                issues.append(Issue("possible_leak", False, n, unit, f"'{ph}' appears in an example report and not in "
                                    "the mission data. If it is a name, place or unit from an old report, remove it."))
        if exempt:
            prev_ids = ids
            continue
        unknown = [i for i in ids if i.upper() not in sources]
        for i in unknown:
            issues.append(Issue("unknown_source", True, n, unit, f"cites {i}, which is not in this mission's data "
                                "(report_sources lists what can be cited)."))
        known = [sources[i.upper()] for i in ids if i.upper() in sources]
        if vals and not ids:
            issues.append(Issue("uncited", True, n, unit, "states " + ", ".join(f"{k} '{v}'" for k, v in vals[:6])
                                + " with no citation. Cite the source, or move it to Questions / gaps."))
        elif vals and known:
            for kind, v in vals:
                ok = any(supported(kind, v, s.text, s.text.lower()) for s in known if s.id != "NOW")
                ok = ok or (any(s.id == "NOW" for s in known) and _now_supports(kind, v, now))
                if not ok:
                    issues.append(Issue("unsupported", True, n, unit, f"{kind} '{v}' is not in the cited source(s) "
                                        f"{', '.join(s.id for s in known)}. Cite the source that has it, correct it, or "
                                        "turn it into a question."))
        for i in ids:  # findings the analyst has not reviewed must be presented as such
            f = (findings or {}).get(i.upper())
            if f and i.upper() not in warned_unreviewed and f.get("verdict") == "unreviewed" and not re.search(r"unreviewed|unconfirmed|not (yet )?reviewed|pending",
                                                                        unit, re.I):
                warned_unreviewed.add(i.upper())
                issues.append(Issue("unreviewed", False, n, unit, f"{i} has no analyst verdict yet; say it is unreviewed."))
        prev_ids = ids
    return issues, cited_all


def render_issues(issues: list[Issue]) -> str:
    blocking = [i for i in issues if i.blocking]
    warn = [i for i in issues if not i.blocking]
    out = [f"Verification: {len(blocking)} blocking problem(s), {len(warn)} warning(s)."]
    if blocking:
        out += ["Blocking (the draft is not saved until each is fixed: cite it, correct it, or make it a question):",
                *[i.render() for i in blocking[:60]]]
        if len(blocking) > 60:
            out.append(f"[... {len(blocking) - 60} more]")
    if warn:
        out += ["Warnings:", *[i.render() for i in warn[:30]]]
    return "\n".join(out)


