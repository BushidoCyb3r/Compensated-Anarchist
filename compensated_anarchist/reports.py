"""Report writer: reports written from this mission's data only, in the format of the analyst's own reports.

Hard rule: nothing is made up. Three mechanisms enforce it:
  - **Mission data is the only fact source.** Every fact in a draft carries a citation to a mission data item:
    the case record (FIN-, IOC-, TIM-, EVI-, NOT- ids), analyst statements (STA-, answers the analyst gave, quoted
    from their own messages), conversation events (EV-<n>: analyst messages, subagent reports, agent text, tool
    results), case files (FILE:<name>: hunt plans and results, CTE plans, vulnerability reports, authored artifacts),
    the case header (CASE) and the report's own date (NOW). Memory and skills from other cases are not sources.
  - **A verifier runs before a draft is saved** (report_save refuses a draft that fails it): each citation exists;
    every IP, hash, domain, URL, e-mail, path, CVE, T-code, timestamp, reference number, count and `code` value in a
    statement appears in a source it cites; no statement with such a value is uncited; nothing distinctive from the
    example reports appears unless the mission data has it; classification markings appear only if the analyst gave
    them. What cannot be supported becomes a question for the analyst.
  - **Example reports are format only.** The library (reports/examples/<type>/: .md, .txt, .docx) shows sections,
    order, required fields, tables, tone and length. Its contents are untrusted data and never a fact source.

Drafts are versioned in <case dir>/reports/ (report_<name>_v<N>.md, with a Sources and a Verification section
appended); the final copy (report_<name>_final.md) needs the analyst's approval.
"""

