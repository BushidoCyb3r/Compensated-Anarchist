W = "{http://schemas.openxmlformats.org/wordprocessingml/2006/main}"


def _docx_part(xml: bytes) -> list[str]:
    root = ET.fromstring(xml)
    body = root.find(f"{W}body")
    lines: list[str] = []

    def para(p: ET.Element) -> str:
        parts = []
        for el in p.iter():
            if el.tag == f"{W}t":
                parts.append(el.text or "")
            elif el.tag == f"{W}tab":
                parts.append("\t")
            elif el.tag in (f"{W}br", f"{W}cr"):
                parts.append("\n")
        text = "".join(parts).strip()
        style = p.find(f"{W}pPr/{W}pStyle")
        sv = (style.get(f"{W}val") or "") if style is not None else ""
        if text and (m := re.match(r"(?i)heading\s?(\d)", sv)):
            return "#" * min(6, int(m.group(1))) + " " + text
        if text and sv.lower() == "title":
            return "# " + text
        if text and p.find(f"{W}pPr/{W}numPr") is not None:
            return "- " + text
        return text

    for el in list(body if body is not None else root):
        if el.tag == f"{W}p":
            lines.append(para(el))
        elif el.tag == f"{W}tbl":
            rows = [[" ".join(para(p) for p in tc.iter(f"{W}p")).strip() for tc in tr.findall(f"{W}tc")]
                    for tr in el.findall(f"{W}tr")]
            if rows:
                lines.append("| " + " | ".join(rows[0]) + " |")
                lines.append("|" + "---|" * len(rows[0]))
                lines += ["| " + " | ".join(r) + " |" for r in rows[1:]]
            lines.append("")
    return lines


def docx_text(data: bytes) -> str:
    """Text of a .docx (headings, paragraphs, lists, tables, headers and footers), with the standard library."""
    z = zipfile.ZipFile(io.BytesIO(data))
    if sum(i.file_size for i in z.infolist()) > 10 * MAX_EXAMPLE_BYTES:
        raise ValueError("document too large to read safely")
    names = z.namelist()
    out = []
    for part in sorted(n for n in names if re.fullmatch(r"word/header\d*\.xml", n)):
        out += [f"[page header] {x}" for x in _docx_part(z.read(part)) if x.strip()]
    out += _docx_part(z.read("word/document.xml"))
    for part in sorted(n for n in names if re.fullmatch(r"word/footer\d*\.xml", n)):
        out += [f"[page footer] {x}" for x in _docx_part(z.read(part)) if x.strip()]
    return re.sub(r"\n{3,}", "\n\n", "\n".join(out)).strip()


def example_text(path: Path) -> str:
    if path.stat().st_size > MAX_EXAMPLE_BYTES:
        raise ValueError(f"{path.name} is too large")
    if path.suffix.lower() == ".docx":
        return docx_text(path.read_bytes())
    return path.read_bytes().decode("utf-8", errors="replace")


def example_files(examples_dir: Path) -> dict[str, list[Path]]:
    """report type (sub-folder; 'general' for files at the top) -> example files."""
    out: dict[str, list[Path]] = {}
    if not examples_dir.is_dir():
        return out
    for p in sorted(examples_dir.rglob("*")):
        if not p.is_file() or p.is_symlink() or p.name.startswith((".", "~$")) or p.name == "README.txt":
            continue
        rel = p.relative_to(examples_dir)
        out.setdefault(rel.parts[0] if len(rel.parts) > 1 else "general", []).append(p)
    return out


def ensure_examples(examples_dir: Path) -> Path:
    examples_dir.mkdir(parents=True, exist_ok=True)
    readme = examples_dir / "README.txt"
    if not readme.exists():
        readme.write_text(EXAMPLES_README, encoding="utf-8")
    return examples_dir


