import subprocess
import sys
import zipfile
from pathlib import Path
from xml.dom import minidom

from starlette.testclient import TestClient

sys.path.insert(0, str(Path(__file__).resolve().parent))
from test_dashboard import H, login, make, wait_for  # noqa: E402

from compensated_anarchist import docx, reports  # noqa: E402

REPORT = """SECRET//REL TO USA, FVEY

# Incident report: ws01

**BLUF:** ws01 beaconed to 203.0.113.9 [FIN-0001, IOC-0001]. The analyst confirmed it [STA-0001].

| Time | Host | Event |
|---|---|---|
| 14:02Z | ws01 | First beacon [TIM-0001] |

1. Quarantine ws01
2. Block 203.0.113.9

`index=zeek` and a <tag> & an ampersand.

<!-- generated by report_save: sources and verification (regenerated on every save) -->

## Sources

- FIN-0001 finding

## Verification

Checked against the mission data.
"""


def parts(data: bytes) -> dict[str, str]:
    z = zipfile.ZipFile(io.BytesIO(data))
    out = {n: z.read(n).decode() for n in z.namelist()}
    for n, x in out.items():
        if n.endswith((".xml", ".rels")):
            minidom.parseString(x)  # every part is well-formed XML
    return out


def test_markdown_to_docx():
    data = docx.to_docx(REPORT, "Incident report", "DRAFT - not yet approved")
    p = parts(data)
    assert {"[Content_Types].xml", "word/document.xml", "word/styles.xml", "word/numbering.xml",
            "word/header1.xml", "word/footer1.xml", "docProps/core.xml"} <= set(p)
    text = reports.docx_text(data)
    assert "[page header] SECRET//REL TO USA, FVEY" in text and "[page footer] SECRET//REL TO USA, FVEY" in text
    assert text.splitlines()[1] == "DRAFT - not yet approved"
    assert "[FIN-0001, IOC-0001]" in text and "| 14:02Z | ws01 | First beacon [TIM-0001] |" in text
    assert "## Sources" in text and "Verification" not in text  # the internal check is not exported
    assert "<tag> & an ampersand" in text  # escaped, never interpreted
    doc = p["word/document.xml"]
    assert '<w:pStyle w:val="Heading1"/>' in doc and "<w:tbl>" in doc and "<w:numId " in doc and '"CodeChar"' in doc
    # no marking on the first line: no header or footer, and none is invented
    plain = parts(docx.to_docx("# Hunt plan\n\nNothing classified here.", "Hunt plan"))
    assert "word/header1.xml" not in plain and "SECRET" not in plain["word/document.xml"]


def test_citation_sources_and_word_export_from_the_dashboard(tmp_path, monkeypatch):
    dash, app = make(tmp_path, monkeypatch, {"lead": [("Done.", [])]})
    with TestClient(app) as c:
        login(c)
        c.post("/api/message", json={"text": "beacon on ws01, contain it"}, headers=H)
        wait_for(c, "run_end")
        h = dash.harness
        h.case.add_finding("Beaconing from ws01", "high", "ws01 beacons to 203.0.113.9.", ["T1071.001"], ["ws01"])
        (h.hunt_plans_dir / "hunt_plan_apt.md").write_text("# Hunt plan APT\n\nLook for beacons.\n")
        (h.reports_dir / "report_ws01_v1.md").write_text(REPORT)
        ev = next(e for e in h.history.events(h.conversation["id"]) if e["kind"] == "analyst_message")

        src = c.get("/api/source/FIN-0001").json()
        assert src["kind"] == "finding" and "203.0.113.9" in src["text"]
        assert "beacon on ws01" in c.get(f"/api/source/EV-{ev['id']}").json()["text"]
        assert c.get("/api/source/FILE:hunt_plan_apt.md").json()["text"].startswith("# Hunt plan APT")
        assert c.get("/api/source/fin-0001").json()["id"] == "FIN-0001"  # ids are case-insensitive, as in the verifier
        for bad in ("FIN-9999", "EV-999999", "FILE:..%2Fcase.json", "FILE:missing.md", "nonsense", "IOC-0001"):
            assert c.get(f"/api/source/{bad}").status_code == 404, bad

        r = c.get("/api/report?format=json").json()
        assert r["name"] == "report_ws01_v1.md" and not r["final"] and "BLUF" in r["text"]
        assert c.get("/api/report").text == REPORT  # the plain form is unchanged

        resp = c.get("/api/plans/report_ws01_v1.md/docx")
        assert resp.status_code == 200 and resp.headers["content-disposition"] == 'attachment; filename="report_ws01_v1.docx"'
        text = reports.docx_text(resp.content)
        assert "DRAFT - not yet approved by the analyst" in text and "[page header] SECRET//REL TO USA, FVEY" in text
        assert c.get("/api/plans/hunt_plan_apt.md/docx").status_code == 200
        assert c.get("/api/plans/nothing.md/docx").status_code == 404
        audit = c.get("/api/audit?limit=50").json()
        exported = [x["data"] for x in audit["records"] if x["event"] == "file_exported"]
        assert {e["file"].rsplit("/", 1)[-1] for e in exported} == {"report_ws01_v1.md", "hunt_plan_apt.md"}
        assert all(e["user"] == "analyst" for e in exported) and audit["verified"]
    # another conversation's case cannot be reached through EV ids
    other = h.history.create("OTHER-CASE")
    eid = h.history.append(other["id"], "s", "analyst_message", {"text": "secret elsewhere"}, 0.0)
    assert h.mission_data().get(f"EV-{eid}") is None


def test_cli_export_docx(tmp_path):
    src = tmp_path / "report_ws01_final.md"
    src.write_text(REPORT)
    run = lambda *a: subprocess.run([sys.executable, "-m", "compensated_anarchist.cli", "export-docx", *a],  # noqa: E731
                                    capture_output=True, text=True, cwd=tmp_path)
    r = run(str(src))
    assert r.returncode == 0, r.stderr
    out = tmp_path / "report_ws01_final.docx"
    assert "DRAFT" not in reports.docx_text(out.read_bytes())  # a final is not marked draft
    assert run(str(src)).returncode != 0  # never overwrites
    assert json.dumps(parts(out.read_bytes())["docProps/core.xml"]).count("Compensated Anarchist") == 1
